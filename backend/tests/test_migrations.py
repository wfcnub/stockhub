"""PostgreSQL integration tests: migrations, model/migration parity, key constraints.

Skipped unless TEST_DATABASE_URL points at a PostgreSQL 18 server (CI service or local).
"""

from collections.abc import Iterator
from datetime import date

import pytest
from alembic import command
from sqlalchemy import create_engine, func, inspect, select, text
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.models import DailyPrice, Index, SyncJob, TechnicalIndicator, Ticker
from tests.conftest import alembic_config

APP_TABLES = {
    "indexes",
    "tickers",
    "prices",
    "key_metrics",
    "technical_indicators",
    "sync_status",
    "sync_jobs",
}


def _tables(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


@pytest.fixture
def session(migrated_url: str) -> Iterator[Session]:
    engine = create_engine(migrated_url)
    with Session(engine) as s:
        yield s
    engine.dispose()


def test_server_is_postgres_18(scratch_db_url: str) -> None:
    engine = create_engine(scratch_db_url)
    with engine.connect() as conn:
        version = conn.execute(text("SHOW server_version_num")).scalar_one()
    engine.dispose()
    assert int(version) >= 180000


def test_upgrade_downgrade_upgrade_roundtrip(scratch_db_url: str) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "head")
    assert _tables(scratch_db_url) == APP_TABLES
    command.downgrade(cfg, "base")
    assert _tables(scratch_db_url) == set()
    command.upgrade(cfg, "head")
    assert _tables(scratch_db_url) == APP_TABLES


def test_models_match_migrations(migrated_url: str) -> None:
    # Raises AutogenerateDiffsDetected if autogenerate would emit any operation.
    command.check(alembic_config(migrated_url))


def _ticker(session: Session) -> Ticker:
    index = Index(code="JCI", name="Jakarta Composite Index", yfinance_suffix=".JK")
    ticker = Ticker(symbol="BBCA", index=index)
    session.add(ticker)
    session.commit()
    return ticker


def test_indicator_natural_key_treats_null_window_as_equal(session: Session) -> None:
    ticker = _ticker(session)
    row = dict(ticker_id=ticker.id, date=date(2026, 1, 2), indicator_type="vwap", value=1.0)
    session.add(TechnicalIndicator(**row, window_period=None))
    session.commit()
    session.add(TechnicalIndicator(**row, window_period=None))
    with pytest.raises(IntegrityError):
        session.commit()
    session.rollback()


def test_indicator_upsert_on_conflict(session: Session) -> None:
    ticker = _ticker(session)
    key = dict(ticker_id=ticker.id, date=date(2026, 1, 2), indicator_type="rsi", window_period=14)
    for value in (40.0, 55.5):
        stmt = insert(TechnicalIndicator).values(**key, value=value)
        stmt = stmt.on_conflict_do_update(
            constraint="uq_technical_indicators_natural_key", set_={"value": stmt.excluded.value}
        )
        session.execute(stmt)
    session.commit()
    rows = session.scalars(select(TechnicalIndicator)).all()
    assert [(r.window_period, r.value) for r in rows] == [(14, 55.5)]


def test_price_natural_key(session: Session) -> None:
    ticker = _ticker(session)
    session.add(DailyPrice(ticker_id=ticker.id, date=date(2026, 1, 2), close=9000.0))
    session.commit()
    session.add(DailyPrice(ticker_id=ticker.id, date=date(2026, 1, 2), close=9100.0))
    with pytest.raises(IntegrityError):
        session.commit()
    session.rollback()


def test_hard_delete_index_cascades_to_tickers_and_jobs(session: Session) -> None:
    ticker = _ticker(session)
    session.add(DailyPrice(ticker_id=ticker.id, date=date(2026, 1, 2), close=9000.0))
    session.add(SyncJob(sync_id="sync_1", index_id=ticker.index_id))
    session.commit()

    session.delete(session.get(Index, ticker.index_id))
    session.commit()

    for model in (Index, Ticker, DailyPrice, SyncJob):
        assert session.scalar(select(func.count()).select_from(model)) == 0


def test_status_check_constraint(session: Session) -> None:
    ticker = _ticker(session)
    session.add(SyncJob(sync_id="sync_bad", index_id=ticker.index_id, status="bogus"))
    with pytest.raises(IntegrityError):
        session.commit()
    session.rollback()
